/** The Twitch category standing behind an Xtreme label, if any. */
export function twitchCategoryFor(label: string): TwitchCategory | undefined {
  const alias = ALIAS[label];
  return (alias && BY_SLUG.get(alias)) || BY_NAME.get(label.toLowerCase());
}

/** Portrait box art for an Xtreme label, or undefined when Twitch has none. */
export function twitchArtFor(label: string, w = 285, h = 380): string | undefined {
  const c = twitchCategoryFor(label);
  return c ? twitchBoxArt(c.artId, w, h) : undefined;
}

