export interface TwitchCategory {
  name: string;
  slug: string;
  /** Twitch box-art id; render with `twitchBoxArt`. */
  artId: string;
  /** Viewers at capture, for ranking only. */
  viewers: number;
  tags: string[];
  /** Twitch's own non-game categories (IRL, Creative, Music…). */
  isGame: boolean;
}

/** Box art at a given size. Twitch serves any WxH; 285×380 is the native card. */
export function twitchBoxArt(artId: string, w = 285, h = 380) {
  return `https://static-cdn.jtvnw.net/ttv-boxart/${artId}-${w}x${h}.jpg`;
}

const NOT_GAMES = new Set(["IRL", "Creative", "Gambling Game", "Educational Game"]);

export const TWITCH_CATEGORIES: TwitchCategory[] = ROWS.map(([name, slug, artId, viewers, tags]) => {
  const t = tags ? tags.split("|") : [];
  return { name, slug, artId, viewers, tags: t, isGame: !t.some((x) => NOT_GAMES.has(x)) && !/^(ZEVENT|Always On|Games \+ Demos|Retro)$/.test(name) };
});

const BY_NAME = new Map(TWITCH_CATEGORIES.map((c) => [c.name.toLowerCase(), c]));
const BY_SLUG = new Map(TWITCH_CATEGORIES.map((c) => [c.slug, c]));

